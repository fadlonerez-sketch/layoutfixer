"""NSPasteboard backend for clipboard.ClipboardGuard (the Mac counterpart of Win32Clipboard).

The general pasteboard's changeCount plays the role of Windows' clipboard
sequence number. A backup keeps every item with every type it offers. Our
temporary text carries the nspasteboard.org markers that clipboard managers
(Maccy, Paste, Alfred, Raycast...) honour, so it never lands in their history.
"""

from __future__ import annotations

import logging
import threading

from ..clipboard import ClipboardError, Snapshot

log = logging.getLogger(__name__)

TEXT_TYPE = "public.utf8-plain-text"  # NSPasteboardTypeString
TRANSIENT_TYPES = ("org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType")


class MacClipboard:
    def __init__(self, pasteboard=None):
        self._pb = pasteboard

    @property
    def pb(self):
        if self._pb is None:
            from AppKit import NSPasteboard
            self._pb = NSPasteboard.generalPasteboard()
        return self._pb

    def _new_item(self):
        from AppKit import NSPasteboardItem
        return NSPasteboardItem.alloc().init()

    def _data(self, payload: bytes = b""):
        from Foundation import NSData
        return NSData.dataWithBytes_length_(payload, len(payload))

    # -- backend interface
    def sequence(self) -> int:
        return int(self.pb.changeCount())

    def snapshot(self, timeout_s: float = 5.0) -> Snapshot:
        """Back up the pasteboard. Promised data is produced by its owner app on request, which can be
        slow or hang, so this runs on a helper thread; past the timeout nothing is changed."""
        box: dict = {}

        def work():
            try:
                box["snap"] = self._snapshot()
            except BaseException as e:  # noqa: BLE001 - handed to the caller
                box["error"] = e

        t = threading.Thread(target=work, name="LayoutFixer-clipboard-backup", daemon=True)
        t.start()
        t.join(timeout_s)
        if t.is_alive():
            raise ClipboardError("the app that owns the clipboard is not responding")
        if "error" in box:
            raise box["error"]
        return box["snap"]

    def _snapshot(self) -> Snapshot:
        snap = Snapshot()
        for index, item in enumerate(self.pb.pasteboardItems() or []):
            for t in item.types() or []:
                data = item.dataForType_(t)
                if data is None:
                    snap.skipped.append(index)
                    continue
                snap.items.append((index, str(t), bytes(data)))
        if snap.skipped:
            log.info("clipboard backup: %d type(s) copied, %d could not be read", len(snap.items), len(snap.skipped))
        return snap

    def restore(self, snap: Snapshot, expected_seq: int | None = None) -> str:
        # NSPasteboard has no lock like OpenClipboard: check as late as possible, right before writing.
        items: dict[int, object] = {}
        for index, type_, payload in snap.items:
            item = items.get(index)
            if item is None:
                item = items[index] = self._new_item()
            item.setData_forType_(self._data(payload), type_)
        ordered = [items[i] for i in sorted(items)]
        if ordered:
            ordered[0].setData_forType_(self._data(), TRANSIENT_TYPES[0])  # already in the managers' history
        if expected_seq is not None and self.sequence() != expected_seq:
            return "changed"
        self.pb.clearContents()
        if not ordered:
            return "restored"
        return "restored" if self.pb.writeObjects_(ordered) else "failed"

    def discard(self, snap: Snapshot) -> None:
        snap.items = []

    def set_text(self, text: str) -> bool:
        item = self._new_item()
        item.setString_forType_(text, TEXT_TYPE)
        for t in TRANSIENT_TYPES:
            item.setData_forType_(self._data(), t)
        self.pb.clearContents()
        return bool(self.pb.writeObjects_([item]))

    def get_text(self) -> str | None:
        s = self.pb.stringForType_(TEXT_TYPE)
        return str(s) if s is not None else None
